import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import { once } from 'node:events';
import assert from 'node:assert/strict';
import { createDatabase, projectRoot } from '../server/db.mjs';
import { createApp } from '../server/app.mjs';
const db=await createDatabase({dataDir:'memory://',demo:true});
const server=createApp(db).listen(0,'127.0.0.1');
await once(server,'listening');
const base='http://127.0.0.1:'+server.address().port;
const screenshots=path.join(projectRoot,'test-results','screenshots');
await mkdir(screenshots,{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const page=await context.newPage();
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
try{
  await page.goto(base,{waitUntil:'domcontentloaded'});
  await page.locator('.login-card').nth(0).click();
  await page.locator('#user-nome').filter({hasText:'Carlos'}).waitFor();
  assert.equal(await page.locator('#nav-banco').isVisible(),false);
  await page.locator('#nav-cham').click();
  await page.locator('tr[onclick="abrirChamado(5)"]').click();
  await page.locator('#ai-box').filter({hasText:'4 ocorrência(s)'}).waitFor();
  await page.screenshot({path:path.join(screenshots,'tecnico-recorrencia.png'),fullPage:true});
  await page.locator('#ed-solucao').fill('Registro fictício: diagnóstico documentado e solução validada no teste de interface.');
  await page.locator('#ed-status').selectOption('resolvido');
  await page.getByRole('button',{name:'Salvar atendimento',exact:true}).click();
  await page.locator('#modal-ov.open').waitFor({state:'hidden'});
  await page.reload({waitUntil:'domcontentloaded'});
  await page.locator('#nav-cham').click();
  await page.locator('tr[onclick="abrirChamado(5)"]').click();
  assert.equal(await page.locator('#ed-status').inputValue(),'resolvido');
  assert.match(await page.locator('.hist-list').innerText(),/Carlos Mendes/);
  await page.locator('.mc').click();
  await page.locator('.sb-logout').click();
  await page.locator('.login-card').nth(2).click();
  await page.locator('#user-nome').filter({hasText:'Fernanda'}).waitFor();
  await page.locator('#nav-banco').click();
  await page.locator('#db-summary').filter({hasText:'PostgreSQL'}).waitFor();
  await page.locator('#db-rows tbody tr').first().waitFor();
  await page.screenshot({path:path.join(screenshots,'supervisor-banco.png'),fullPage:true});
  await page.locator('#nav-elevadores').click();
  await page.locator('#local-nome').fill('Local fictício cadastrado no navegador');
  await page.locator('#local-endereco').fill('Endereço fictício para teste');
  await page.locator('#local-bairro').fill('Barra da Tijuca');
  await page.getByRole('button',{name:'Cadastrar local',exact:true}).click();
  await page.locator('#lift-local option').filter({hasText:'Local fictício cadastrado'}).waitFor({state:'attached'});
  await page.locator('#lift-local').selectOption({label:'Local fictício cadastrado no navegador'});
  await page.locator('#lift-codigo').fill('BAR-TESTE');
  await page.locator('#lift-fabricante').fill('Fabricante fictício');
  await page.locator('#lift-modelo').fill('Modelo demonstrativo');
  await page.locator('#lift-serie').fill('DEMO-BROWSER');
  await page.getByRole('button',{name:'Cadastrar elevador',exact:true}).click();
  await page.locator('#lift-list').filter({hasText:'BAR-TESTE'}).waitFor();
  await page.locator('#nav-novo').click();
  await page.locator('#nc-titulo').fill('<img src=x onerror="window.__xss=1"> Porta travando');
  await page.locator('#nc-elevador').selectOption('1');
  await page.locator('#nc-sla').fill('8');
  await page.locator('#fs1').getByRole('button').click();
  await page.locator('#nc-desc').fill('Porta interrompe o fechamento e sensor intermitente.');
  await page.locator('#nc-tec').selectOption('TK-CAP-001');
  await page.locator('#fs2').getByRole('button',{name:/Próximo/}).click();
  await page.locator('#btn-abrir').click();
  await page.locator('#modal-ov.open').waitFor();
  assert.equal(await page.locator('img[src="x"]').count(),0);
  assert.equal(await page.evaluate(()=>window.__xss),undefined);
  await page.locator('.mc').click();
  await page.locator('#nav-imp').click();
  await page.locator('#f-inp').setInputFiles({name:'quoted.csv',mimeType:'text/csv',buffer:Buffer.from('titulo,elevador_codigo,descricao\n"Teste, com vírgula",BAR-001,"Descrição em duas\nlinhas"\n')});
  await page.locator('#import-submit').click();
  await page.locator('#imp-res').filter({hasText:'1 importados'}).waitFor();
  const mobileContext=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'});
  const mobile=await mobileContext.newPage();
  mobile.on('pageerror',error=>errors.push(error.message));
  await mobile.goto(base,{waitUntil:'domcontentloaded'});
  await mobile.locator('.login-card').nth(2).click();
  await mobile.locator('#page-dashboard.active').waitFor();
  await mobile.screenshot({path:path.join(screenshots,'dashboard-mobile.png'),fullPage:true});
  assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth+1),'Layout mobile não deve ultrapassar a largura da tela.');
  await mobile.locator('.mtb-burger').click();
  await mobile.locator('#nav-elevadores').click();
  await mobile.locator('#lift-list').filter({hasText:'BAR-001'}).waitFor();
  await mobileContext.close();
  assert.deepEqual(errors,[]);
  console.log('Browser: login, recorrência, encerramento, sessão após reload, banco, cadastro, importação CSV e layout mobile verificados.');
  console.log('Capturas: '+screenshots);
}finally{
  await browser.close();
  await new Promise(r=>server.close(r));
  await db.close();
}
