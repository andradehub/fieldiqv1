import { cp, mkdir, rm } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const output=path.resolve(root,'public');
if(path.dirname(output)!==path.resolve(root)||path.basename(output)!=='public')throw new Error('Diretório de build inesperado.');
await rm(output,{recursive:true,force:true});
await cp(path.join(root,'fieldiqarchives','public'),path.join(root,'public'),{recursive:true});
await mkdir(path.join(root,'public','vendor'),{recursive:true});
await cp(path.join(root,'node_modules','chart.js','dist','chart.umd.js'),path.join(root,'public','vendor','chart.umd.js'));
await cp(path.join(root,'node_modules','lucide','dist','umd','lucide.min.js'),path.join(root,'public','vendor','lucide.js'));
await mkdir(path.join(root,'public','assets','fonts'),{recursive:true});
await cp(path.join(root,'node_modules','@fontsource-variable','inter','files','inter-latin-wght-normal.woff2'),path.join(root,'public','assets','fonts','inter-latin-wght-normal.woff2'));
await mkdir(path.join(root,'public','licenses'),{recursive:true});
await cp(path.join(root,'node_modules','lucide','LICENSE'),path.join(root,'public','licenses','Lucide.txt'));
await cp(path.join(root,'node_modules','@fontsource-variable','inter','LICENSE'),path.join(root,'public','licenses','Inter.txt'));
console.log('Interface, ícones, tipografia e gráficos preparados em public/. A API precisa de DATABASE_URL na nuvem.');
